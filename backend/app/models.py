"""WebSage AI — API Schemas & Data Models.

Defines Pydantic models matching the API contract approved in Requirements v1.2.
"""

from pydantic import BaseModel, HttpUrl, Field
from typing import Optional


class SummarizeRequest(BaseModel):
    """Request model for POST /api/summarize."""

    url: str = Field(
        ...,
        description="Publicly accessible HTTP/HTTPS webpage URL",
        min_length=1,
        max_length=2048,
        examples=["https://example.com/article"],
    )


class SummarizeResponse(BaseModel):
    """Success response model for POST /api/summarize."""

    summary: str = Field(..., description="Concise summary generated by the AI provider")
    source_url: str = Field(..., description="Validated source URL")
    source_host: str = Field(..., description="Hostname of the source webpage")
    extracted_characters: int = Field(..., description="Number of readable characters extracted from HTML")


class ErrorDetail(BaseModel):
    """Inner error detail representation."""

    code: str = Field(..., description="Standardized error code")
    message: str = Field(..., description="Human-readable safe error message")


class ErrorResponse(BaseModel):
    """Standardized error response matching Requirements v1.2."""

    error: ErrorDetail


class HealthResponse(BaseModel):
    """Response model for GET /health."""

    status: str = Field(default="ok", description="Health check status indicator")
